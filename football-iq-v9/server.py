@app.post("/api/score")
def update_score(payload: ScorePayload, user: Mapping[str, Any] = Depends(current_user)):
    user_id = int(user["id"])
    stats_json = json.dumps(payload.stats, ensure_ascii=False, separators=(",", ":"))
    wins = int(payload.stats.get("onlineWins", 0) or 0)
    losses = int(payload.stats.get("onlineLosses", 0) or 0)
    now = int(time.time())
    with db() as c:
        existing = c.execute(
            text("SELECT xp,level,online_wins,online_losses FROM scores WHERE user_id=:user_id"),
            {"user_id": user_id},
        ).mappings().first()
        if existing:
            c.execute(
                text(
                    """
                    UPDATE scores SET xp=:xp, level=:level, coins=:coins,
                        online_wins=:online_wins, online_losses=:online_losses,
                        stats_json=:stats_json, updated_at=:updated_at
                    WHERE user_id=:user_id
                    """
                ),
                {
                    "user_id": user_id,
                    "xp": max(int(existing["xp"]), payload.xp),
                    "level": max(int(existing["level"]), payload.level),
                    "coins": payload.coins,
                    "online_wins": max(int(existing["online_wins"]), wins),
                    "online_losses": max(int(existing["online_losses"]), losses),
                    "stats_json": stats_json,
                    "updated_at": now,
                },
            )
        else:
            c.execute(
                text(
                    """
                    INSERT INTO scores(user_id,xp,level,coins,online_wins,online_losses,stats_json,updated_at)
                    VALUES(:user_id,:xp,:level,:coins,:online_wins,:online_losses,:stats_json,:updated_at)
                    """
                ),
                {
                    "user_id": user_id,
                    "xp": payload.xp,
                    "level": payload.level,
                    "coins": payload.coins,
                    "online_wins": wins,
                    "online_losses": losses,
                    "stats_json": stats_json,
                    "updated_at": now,
                },
            )
    return {"ok": True}


@app.get("/api/leaderboard")
def leaderboard(limit: int = 50):
    limit = max(1, min(limit, 100))
    with db() as c:
        rows = c.execute(
            text(
                """
                SELECT u.username,s.xp,s.level,s.online_wins,s.online_losses,s.updated_at
                FROM scores s JOIN users u ON u.id=s.user_id
                ORDER BY s.xp DESC, s.online_wins DESC, s.updated_at ASC
                LIMIT :limit
                """
            ),
            {"limit": limit},
        ).mappings().all()
    return {"items": [dict(r) for r in rows]}


@app.put("/api/save")
def put_save(payload: SavePayload, user: Mapping[str, Any] = Depends(current_user)):
    user_id = int(user["id"])
    raw = json.dumps(payload.data, ensure_ascii=False, separators=(",", ":"))
    if len(raw.encode()) > 2_000_000:
        raise HTTPException(413, "save too large")
    now = int(time.time())
    with db() as c:
        exists = c.execute(
            text("SELECT 1 FROM saves WHERE user_id=:user_id"), {"user_id": user_id}
        ).first()
        if exists:
            c.execute(
                text("UPDATE saves SET data_json=:data_json,updated_at=:updated_at WHERE user_id=:user_id"),
                {"data_json": raw, "updated_at": now, "user_id": user_id},
            )
        else:
            c.execute(
                text("INSERT INTO saves(user_id,data_json,updated_at) VALUES(:user_id,:data_json,:updated_at)"),
                {"user_id": user_id, "data_json": raw, "updated_at": now},
            )
    return {"ok": True, "updated_at": now}


@app.get("/api/save")
def get_save(user: Mapping[str, Any] = Depends(current_user)):
    with db() as c:
        row = c.execute(
            text("SELECT data_json,updated_at FROM saves WHERE user_id=:user_id"),
            {"user_id": int(user["id"])},
        ).mappings().first()
    if not row:
        return {"data": None, "updated_at": None}
    try:
        data = json.loads(row["data_json"])
    except json.JSONDecodeError:
        data = None
    return {"data": data, "updated_at": row["updated_at"]}


class RoomHub:
    def __init__(self) -> None:
        self.rooms: dict[str, dict[str, WebSocket]] = {}

    async def connect(self, room: str, name: str, ws: WebSocket) -> bool:
        room = room.upper()
        members = self.rooms.setdefault(room, {})
        if name not in members and len(members) >= 2:
            await ws.accept()
            await ws.send_json({"type": "error", "message": "room full"})
            await ws.close(code=4003)
            return False
        await ws.accept()
        members[name] = ws
        await self.broadcast(room, {"type": "presence", "count": len(members), "players": list(members)})
        return True

    async def disconnect(self, room: str, name: str) -> None:
        room = room.upper()
        members = self.rooms.get(room, {})
        members.pop(name, None)
        if not members:
            self.rooms.pop(room, None)
            return
        await self.broadcast(room, {"type": "peer_left", "name": name})
        await self.broadcast(room, {"type": "presence", "count": len(members), "players": list(members)})

    async def broadcast(self, room: str, payload: dict[str, Any]) -> None:
        dead: list[str] = []
        for name, ws in list(self.rooms.get(room.upper(), {}).items()):
            try:
                await ws.send_json(payload)
            except Exception:
                dead.append(name)
        for name in dead:
            self.rooms.get(room.upper(), {}).pop(name, None)


hub = RoomHub()


@app.websocket("/ws/{room}/{name}")
async def room_socket(ws: WebSocket, room: str, name: str, token: str | None = None):
    room = room.strip().upper()[:8]
    name = name.strip()[:32] or "Guest"
    user = user_for_token(token)
    if user:
        name = user["username"]
    connected = await hub.connect(room, name, ws)
    if not connected:
        return
    try:
        while True:
            data = await ws.receive_json()
            if not isinstance(data, dict):
                continue
            msg_type = str(data.get("type", ""))[:32]
            if msg_type not in {"start", "answer", "ping", "chat"}:
                continue
            safe = {"type": msg_type, "sender": name}
            if msg_type == "start":
                indices = data.get("indices", [])
                if isinstance(indices, list):
                    safe["indices"] = [int(x) for x in indices[:10] if (isinstance(x, int) or str(x).isdigit()) and 0 <= int(x) < 12]
            elif msg_type == "answer":
                safe["correct"] = bool(data.get("correct"))
                safe["index"] = int(data.get("index", 0))
            elif msg_type == "chat":
                safe["message"] = str(data.get("message", ""))[:280]
            else:
                safe["ts"] = int(time.time() * 1000)
            await hub.broadcast(room, safe)
    except WebSocketDisconnect:
        await hub.disconnect(room, name)
    except Exception:
        await hub.disconnect(room, name)
        try:
            await ws.close()
        except Exception:
            pass


