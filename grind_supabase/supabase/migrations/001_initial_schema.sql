create table if not exists public.user_game_ranks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  game_id bigint not null references public.games(id) on delete cascade,
  rank_name text not null,
  points integer not null default 0 check (points >= 0),
  wins integer not null default 0 check (wins >= 0),
  losses integer not null default 0 check (losses >= 0),
  updated_at timestamptz not null default now(),
  unique(user_id, game_id)
);

create index if not exists user_game_ranks_user_idx on public.user_game_ranks(user_id);

create table if not exists public.lobbies (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  game_id bigint references public.games(id) on delete set null,
  name text not null check (char_length(name) between 2 and 80),
  description text,
  visibility text not null default 'public' check (visibility in ('public','private','friends')),
  max_members integer not null default 5 check (max_members between 2 and 100),
  status text not null default 'open' check (status in ('open','full','closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists lobbies_owner_idx on public.lobbies(owner_id);
create index if not exists lobbies_status_idx on public.lobbies(status);

create table if not exists public.lobby_members (
  lobby_id uuid not null references public.lobbies(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member' check (role in ('owner','moderator','member')),
  joined_at timestamptz not null default now(),
  primary key(lobby_id, user_id)
);

create index if not exists lobby_members_user_idx on public.lobby_members(user_id);

alter table public.profiles enable row level security;
