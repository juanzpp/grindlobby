@app.post("/api/register")
def register(payload: AuthPayload):
    username = payload.username.strip()
    salt = secrets.token_hex(16)
    digest = password_digest(payload.password, salt)
    now = int(time.time())
    try:
        with db() as c:
            user_id = c.execute(
                text(
                    """
                    INSERT INTO users(username,salt,password_hash,created_at)
                    VALUES(:username,:salt,:password_hash,:created_at)
                    RETURNING id
                    """
                ),
                {"username": username, "salt": salt, "password_hash": digest, "created_at": now},
            ).scalar_one()
            c.execute(
                text(
                    """
                    INSERT INTO scores(user_id,xp,level,coins,online_wins,online_losses,stats_json,updated_at)
                    VALUES(:user_id,0,1,0,0,0,'{}',:updated_at)
                    """
                ),
                {"user_id": int(user_id), "updated_at": now},
            )
    except IntegrityError:
        raise HTTPException(409, "username already exists")
    token = make_session(int(user_id))
    return {"token": token, "user": {"id": int(user_id), "username": username}}


@app.post("/api/login")
def login(payload: AuthPayload):
    username = payload.username.strip()
    with db() as c:
        user = c.execute(
            text("SELECT * FROM users WHERE LOWER(username)=LOWER(:username)"),
            {"username": username},
        ).mappings().first()
    if not user:
        raise HTTPException(401, "invalid username or password")
    candidate = password_digest(payload.password, user["salt"])
    if not hmac.compare_digest(candidate, user["password_hash"]):
        raise HTTPException(401, "invalid username or password")
    token = make_session(int(user["id"]))
    return {"token": token, "user": {"id": int(user["id"]), "username": user["username"]}}


