@contextmanager
def db():
    with engine.begin() as conn:
        yield conn


def init_db() -> None:
    is_pg = DB_DIALECT == "postgresql"
    id_col = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if is_pg else "INTEGER PRIMARY KEY AUTOINCREMENT"
    user_id_type = "BIGINT" if is_pg else "INTEGER"
    username_col = "TEXT NOT NULL" if is_pg else "TEXT NOT NULL UNIQUE COLLATE NOCASE"

    statements = [
        f"""
        CREATE TABLE IF NOT EXISTS users (
            id {id_col},
            username {username_col},
            salt TEXT NOT NULL,
            password_hash TEXT NOT NULL,
            created_at BIGINT NOT NULL
        )
        """,
        f"""
        CREATE TABLE IF NOT EXISTS sessions (
            token_hash TEXT PRIMARY KEY,
            user_id {user_id_type} NOT NULL,
            expires_at BIGINT NOT NULL,
            FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
        )
        """,
        f"""
        CREATE TABLE IF NOT EXISTS scores (
            user_id {user_id_type} PRIMARY KEY,
            xp BIGINT NOT NULL DEFAULT 0,
            level INTEGER NOT NULL DEFAULT 1,
            coins BIGINT NOT NULL DEFAULT 0,
            online_wins BIGINT NOT NULL DEFAULT 0,
            online_losses BIGINT NOT NULL DEFAULT 0,
            stats_json TEXT NOT NULL DEFAULT '{{}}',
            updated_at BIGINT NOT NULL,
            FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
        )
        """,
        f"""
        CREATE TABLE IF NOT EXISTS saves (
            user_id {user_id_type} PRIMARY KEY,
            data_json TEXT NOT NULL,
            updated_at BIGINT NOT NULL,
            FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
        )
        """,
    ]

    with engine.begin() as c:
        if DB_DIALECT == "sqlite":
            c.execute(text("PRAGMA journal_mode=WAL"))
            c.execute(text("PRAGMA foreign_keys=ON"))
        for statement in statements:
            c.execute(text(statement))
        if is_pg:
            c.execute(text("CREATE UNIQUE INDEX IF NOT EXISTS users_username_ci ON users (LOWER(username))"))
        c.execute(text("CREATE INDEX IF NOT EXISTS sessions_expires_idx ON sessions (expires_at)"))
        c.execute(text("CREATE INDEX IF NOT EXISTS scores_rank_idx ON scores (xp DESC, online_wins DESC, updated_at ASC)"))


init_db()


class AuthPayload(BaseModel):
    username: str = Field(min_length=3, max_length=24, pattern=r"^[A-Za-z0-9_.-]+$")
    password: str = Field(min_length=6, max_length=128)


class ScorePayload(BaseModel):
    xp: int = Field(ge=0, le=100_000_000)
    level: int = Field(ge=1, le=10_000)
    coins: int = Field(ge=0, le=100_000_000)
    stats: dict[str, Any] = Field(default_factory=dict)


class SavePayload(BaseModel):
    data: dict[str, Any]


def password_digest(password: str, salt_hex: str) -> str:
    return hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt_hex), 210_000).hex()


def hash_token(token: str) -> str:
    return hashlib.sha256(token.encode()).hexdigest()


def make_session(user_id: int) -> str:
    token = secrets.token_urlsafe(32)
    now = int(time.time())
    with db() as c:
        c.execute(text("DELETE FROM sessions WHERE expires_at < :now"), {"now": now})
        c.execute(
            text("INSERT INTO sessions(token_hash,user_id,expires_at) VALUES(:token_hash,:user_id,:expires_at)"),
            {"token_hash": hash_token(token), "user_id": user_id, "expires_at": now + TOKEN_TTL},
        )
    return token


def user_for_token(token: str | None) -> Mapping[str, Any] | None:
    if not token:
        return None
    with db() as c:
        return c.execute(
            text(
                """
                SELECT u.* FROM sessions s
                JOIN users u ON u.id=s.user_id
                WHERE s.token_hash=:token_hash AND s.expires_at>=:now
                """
            ),
            {"token_hash": hash_token(token), "now": int(time.time())},
        ).mappings().first()


def current_user(authorization: str | None = Header(default=None)) -> Mapping[str, Any]:
    if not authorization or not authorization.lower().startswith("bearer "):
        raise HTTPException(401, "authentication required")
    user = user_for_token(authorization.split(" ", 1)[1].strip())
    if not user:
        raise HTTPException(401, "invalid or expired session")
    return user


