alter table public.lobbies enable row level security;
alter table public.lobby_members enable row level security;

create policy "users view own profile"
on public.profiles for select
to authenticated
using ((select auth.uid()) = id);

create or replace view public.public_profiles
with (security_invoker = true)
as select id, username, display_name, avatar, status, last_seen_at, created_at
from public.profiles;

create policy "users update own profile"
on public.profiles for update
to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

create policy "games readable by everyone"
on public.games for select
to anon, authenticated
using (true);

create policy "ranks readable by authenticated users"
on public.user_game_ranks for select
to authenticated
using (true);

create policy "users manage own ranks"
on public.user_game_ranks for insert
to authenticated
with check ((select auth.uid()) = user_id);

create policy "users update own ranks"
on public.user_game_ranks for update
to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "open lobbies readable by authenticated users"
on public.lobbies for select
to authenticated
using (visibility = 'public' or owner_id = (select auth.uid()));

create policy "users create own lobbies"
on public.lobbies for insert
to authenticated
with check (owner_id = (select auth.uid()));

create policy "owners update lobbies"
on public.lobbies for update
to authenticated
using (owner_id = (select auth.uid()))
with check (owner_id = (select auth.uid()));

create policy "owners delete lobbies"
on public.lobbies for delete
to authenticated
using (owner_id = (select auth.uid()));

create policy "members can view memberships"
on public.lobby_members for select
to authenticated
using (
  user_id = (select auth.uid())
  or exists (
    select 1 from public.lobbies l
    where l.id = lobby_id and (l.visibility = 'public' or l.owner_id = (select auth.uid()))
  )
);

create policy "users join lobbies as themselves"
on public.lobby_members for insert
to authenticated
with check (user_id = (select auth.uid()));

create policy "users leave lobby"
on public.lobby_members for delete
to authenticated
using (
  user_id = (select auth.uid())
  or exists (select 1 from public.lobbies l where l.id = lobby_id and l.owner_id = (select auth.uid()))
);
